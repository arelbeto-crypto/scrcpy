#!/usr/bin/env python3
"""Compile MediaPipe's Apache-2.0 canonical OBJ into shared face UVs/topology."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'assets/upstream/canonical_face_model.obj'
TARGET = ROOT / 'common/java/com/poco/vision/FaceTopology.java'


def compile_model():
    vertices, texcoords, faces = [], [], []
    for line in SOURCE.read_text().splitlines():
        tokens = line.split()
        if not tokens:
            continue
        if tokens[0] == 'v':
            vertices.append(tuple(map(float, tokens[1:4])))
        elif tokens[0] == 'vt':
            texcoords.append(tuple(map(float, tokens[1:3])))
        elif tokens[0] == 'f':
            faces.append([tuple(int(x) - 1 for x in p.split('/')[:2]) for p in tokens[1:]])
    assert len(vertices) == 468
    uv = [None] * 468
    indices = []
    for face in faces:
        assert len(face) == 3
        for vertex, texture in face:
            value = texcoords[texture]
            assert uv[vertex] is None or uv[vertex] == value, 'UV seam needs expanded topology'
            uv[vertex] = value
            indices.append(vertex)
    assert all(p is not None for p in uv)
    return vertices, uv, indices


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    vertices, uv, indices = compile_model()
    def rows(values, width=12):
        return '\n'.join('        ' + ', '.join(values[i:i+width]) + ',' for i in range(0, len(values), width))
    result = '''// Generated by build_face_topology.py. Source: MediaPipe canonical_face_model.obj.
// Copyright The MediaPipe Authors. Apache-2.0; see assets/upstream/MEDIAPIPE-LICENSE.txt.
package com.poco.vision;

public final class FaceTopology {
    private FaceTopology() { }
    public static final int VERTEX_COUNT = 468;
    public static final float[] UV = {
''' + rows([f'{v:.6f}f' for pair in uv for v in pair]) + '''
    };
    public static final float[] CANONICAL = {
''' + rows([f'{v:.6f}f' for vertex in vertices for v in vertex]) + '''
    };
    public static final short[] TRIANGLES = {
''' + rows(list(map(str, indices)), 18) + '''
    };
}
'''
    if args.check:
        assert TARGET.read_text() == result, 'Regenerate FaceTopology.java'
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(result)
    print(f'Face topology: {len(uv)} UV vertices, {len(indices)//3} triangles')


if __name__ == '__main__':
    main()
