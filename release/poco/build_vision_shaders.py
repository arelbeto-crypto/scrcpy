#!/usr/bin/env python3
"""Embed the canonical, independently testable GLES shader sources in the Android server."""
from pathlib import Path
import json
import sys

root = Path(__file__).resolve().parent / 'v84'
sources = [('VERTEX', 'composite.vert'), ('FRAGMENT', 'composite.frag'),
           ('MESH_VERTEX', 'mesh.vert'), ('MESH_FRAGMENT', 'mesh.frag')]
text = 'package com.genymobile.scrcpy.opengl;\n\n// Generated by build_vision_shaders.py; edit v84/shaders instead.\nfinal class VisionShaders {\n'
for name, filename in sources:
    lines = (root / 'shaders' / filename).read_text().splitlines(keepends=True)
    text += '    static final String ' + name + ' =\n'
    text += '\n'.join('            ' + ('+ ' if i else '') + json.dumps(line) for i, line in enumerate(lines)) + ';\n'
text += '    private VisionShaders() { }\n}\n'
target = root / 'VisionShaders.java'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('Embedded vision shaders are out of date')
else:
    target.write_text(text)
